// Scans public/images/products/ and writes src/config/photos.generated.ts.
// Name photos after the product's web address: 82mm-2-5-track.jpg, 82mm-2-5-track-2.jpg, sliding-windows.webp …
// Runs automatically before `npm run dev` and `npm run build`.
import { readdirSync, writeFileSync } from "node:fs";
const dir = "public/images/products";
const map = {};
for (const f of readdirSync(dir).sort((a, b) => a.localeCompare(b, "en", { numeric: true }))) {
  const m = f.match(/^(.+?)(?:-(\d+))?\.(jpe?g|png|webp|avif)$/i);
  if (!m) continue;
  (map[m[1]] ??= []).push(`/images/products/${f}`);
}
writeFileSync("src/config/photos.generated.ts",
  `// Generated by scripts/photos.mjs: do not edit. Add files to public/images/products/ instead.\nexport const productPhotos: Record<string, string[]> = ${JSON.stringify(map, null, 2)};\n`);
console.log(`photos: ${Object.values(map).flat().length} photo(s) for ${Object.keys(map).length} product(s)`);
