// Scans public/images/products/ (real photos) and public/images/3d/ (3D illustrations)
// and writes src/config/photos.generated.ts. Real photos always win over renders.
// Name files after the product's web address: 82mm-2-5-track.jpg, 82mm-2-5-track-2.jpg, sliding-windows.webp …
// Runs automatically before `npm run dev` and `npm run build`.
import { readdirSync, writeFileSync, existsSync } from "node:fs";
function scan(dir, url) {
  const map = {};
  if (!existsSync(dir)) return map;
  for (const f of readdirSync(dir).sort((a, b) => a.localeCompare(b, "en", { numeric: true }))) {
    const m = f.match(/^(.+?)(?:-(\d+))?\.(jpe?g|png|webp|avif)$/i);
    if (m) (map[m[1]] ??= []).push(`${url}/${f}`);
  }
  return map;
}
const photos = scan("public/images/products", "/images/products");
const renders = scan("public/images/3d", "/images/3d");
writeFileSync("src/config/photos.generated.ts",
  `// Generated by scripts/photos.mjs: do not edit. Add files to public/images/products/ instead.\n` +
  `export const productPhotos: Record<string, string[]> = ${JSON.stringify(photos, null, 2)};\n` +
  `export const productRenders: Record<string, string[]> = ${JSON.stringify(renders, null, 2)};\n`);
console.log(`photos: ${Object.values(photos).flat().length} photo(s), ${Object.values(renders).flat().length} 3D illustration(s)`);
